# модель говорит о себе / о клиенте в третьем лице — клиенту это не показываем
SELF_TALK_RE = re.compile(
    r"(?i)\b(?:я\s+как\s+(?:ассистент|консультант)|как\s+(?:ассистент|консультант)|мне\s+нужно|я\s+должен)\b"
)
# зачин инструкции оператору: «правильно объяснять так:»
OPERATOR_LEAD_RE = re.compile(r"(?i)^\s*(?:правильно|лучше|нужно)\s+(?:объяснять|говорить|отвечать)[^:]*:\s*")
# инструкция оператору внутри абзаца: «это не нужно зачитывать»
OPERATOR_SENTENCE_RE = re.compile(r"(?i)(?:не\s+нужно|нельзя)\s+(?:зачитывать|говорить|упоминать)")


def booked_text(profile: ClientProfile, head: str) -> str:
    """Подтверждение записи из профиля, а не из ответа модели."""
    phone = profile.phone or "указанному номеру"
    when = profile.consultation_time or "согласованное время"
    return (
        f"{head + chr(10) + chr(10) if head else ''}Записал вас на консультацию: юрист позвонит на {phone}, "
        f"время — {when}. Подготовьте, пожалуйста, паспорт, список кредиторов с суммами и справки о доходах."
    )


def known_facts(profile: ClientProfile) -> list[str]:
    """Что уже известно о клиенте — для плашки «известно» (сейчас скрыто в контракте)."""
    facts: list[str] = []
    if profile.debt_amount is not None:
        facts.append(f"сумма долга: {profile.debt_amount} ₽")
    if profile.region:
        facts.append(f"регион: {profile.region}")
    if profile.phone:
        facts.append(f"телефон: {profile.phone}")
    if profile.consultation_time:
        facts.append(f"время: {profile.consultation_time}")
    return facts
