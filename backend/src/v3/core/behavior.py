# ── страж: слова внутренней кухни, которых клиент видеть не должен ────────────
INTERNAL_WORDS: tuple[str, ...] = ("инструкц", "фрагмент", "источник", "база знаний", "выдержк", "контекст")


def leaks_internals(text: str) -> bool:
    """Есть ли в тексте слова, выдающие внутренний механизм ответа."""
    lowered = text.casefold()
    return any(word in lowered for word in INTERNAL_WORDS)
