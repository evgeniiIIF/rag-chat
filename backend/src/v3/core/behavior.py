def _missing_hint(profile: ClientProfile) -> str:
    missing = profile.missing_filter()
    return f"В конце задай один вопрос: {MISSING_HINTS[missing]}." if missing else ""


def _offer_guard(profile: ClientProfile) -> str:
    """Запись предлагаем только прошедшим фильтры; провал фильтра запрещает оффер на любом шаге."""
    if profile.missing_filter() is not None or profile.filters_ok():
        return ""
    return "Клиент не проходит условия компании: не предлагай консультацию, звонок и не проси телефон."


def _phone_guard(profile: ClientProfile) -> str:
    """Номер назван, но не распознан: просим назвать ещё раз."""
    if profile.phone is not None or not profile.phone_raw:
        return ""
    return (
        "Номер телефона клиента не распознан (подходят номера из 6, 10 или 11 цифр): "
        "вежливо попроси назвать его ещё раз."
    )


def build_system_prompt(step: str, profile: ClientProfile) -> str:
    """Системный промпт хода: роль + инструкция шага + поправки по профилю. Собирается здесь и только здесь."""
    parts = [SYSTEM_PROMPT, STAGE_INSTRUCTIONS.get(step, "")]
    # на шагах ask_debt/ask_region о недостающем фильтре уже говорит инструкция шага
    if step == "rag":
        parts.append(_missing_hint(profile))
    parts += [_offer_guard(profile), _phone_guard(profile)]
    return "\n\n".join(part for part in parts if part)


# заголовок знаний компании в сообщении: без слов «документ», «источник», «фрагмент»
FRAGMENTS_HEADER = "Что знает компания по этому вопросу:"
FILTERS_LABEL = "Состояние фильтров"
CLIENT_LABEL = "Что известно о клиенте"
QUESTION_LABEL = "Текущая реплика клиента"
HISTORY_TOKEN_BUDGET = 2000


def _rub(amount: int) -> str:
    return f"{amount:,}".replace(",", " ")


def filter_state_text(profile: ClientProfile) -> str:
    """Состояние фильтров словами для промпта."""
    if profile.debt_amount is None:
        debt = "не указан"
    elif qualifies_by_debt(profile.debt_amount):
        debt = f"{profile.debt_amount} ₽ (подходит)"
    else:
        debt = f"{profile.debt_amount} ₽ (меньше {_rub(MIN_DEBT_RUB)} ₽)"
    if profile.region is None:
        region = "не указан"
    elif is_excluded_region(profile.region):
        region = f"{profile.region} (не обслуживается)"
    else:
        region = f"{profile.region} (подходит)"
    passed = "пройдены" if profile.filters_ok() else "не пройдены"
    return f"долг: {debt}; регион: {region}; фильтры: {passed}"


def profile_text(profile: ClientProfile) -> str:
    """Что известно о клиенте, для промпта."""
    parts: list[str] = []
    if profile.debt_amount is not None:
        parts.append(f"сумма долга: {profile.debt_amount} ₽")
    if profile.region:
        parts.append(f"регион: {profile.region}")
    if profile.phone:
        parts.append(f"телефон: {profile.phone}")
    elif profile.phone_raw:
        parts.append(f"телефон назван неполно: {profile.phone_raw}")
    if profile.consultation_time:
        parts.append(f"удобное время: {profile.consultation_time}")
    if profile.facts:
        parts.append("; ".join(f"{key}: {value}" for key, value in profile.facts.items()))
    return "; ".join(parts) if parts else "(пока ничего)"


def build_user_message(*, question: str, profile: ClientProfile, fragments: str) -> str:
    """Реплика для модели: фильтры → что знаем о клиенте → знания компании → вопрос."""
    parts = [f"{FILTERS_LABEL}: {filter_state_text(profile)}", f"{CLIENT_LABEL}: {profile_text(profile)}"]
    if fragments:
        parts.append(f"{FRAGMENTS_HEADER}\n{fragments}")
    parts.append(f"{QUESTION_LABEL}: {question.strip()}")
    return "\n\n".join(parts)


