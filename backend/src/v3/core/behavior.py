def _missing_hint(profile: ClientProfile) -> str:
    missing = profile.missing_filter()
    return f"В конце задай один вопрос: {MISSING_HINTS[missing]}." if missing else ""


def _offer_guard(profile: ClientProfile) -> str:
    """Запись предлагаем только прошедшим фильтры; провал фильтра запрещает оффер на любом шаге."""
    if profile.missing_filter() is not None or profile.filters_ok():
        return ""
    return "Клиент не проходит условия компании: не предлагай консультацию, звонок и не проси телефон."


def _phone_guard(profile: ClientProfile) -> str:
    """Номер назван, но не распознан: просим назвать ещё раз."""
    if profile.phone is not None or not profile.phone_raw:
        return ""
    return (
        "Номер телефона клиента не распознан (подходят номера из 6, 10 или 11 цифр): "
        "вежливо попроси назвать его ещё раз."
    )


def build_system_prompt(step: str, profile: ClientProfile) -> str:
    """Системный промпт хода: роль + инструкция шага + поправки по профилю. Собирается здесь и только здесь."""
    parts = [SYSTEM_PROMPT, STAGE_INSTRUCTIONS.get(step, "")]
    # на шагах ask_debt/ask_region о недостающем фильтре уже говорит инструкция шага
    if step == "rag":
        parts.append(_missing_hint(profile))
    parts += [_offer_guard(profile), _phone_guard(profile) if step == "invite" else ""]
    return "\n\n".join(part for part in parts if part)


