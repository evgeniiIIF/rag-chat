def _rub(amount: int) -> str:
    return f"{amount:,}".replace(",", " ")


def filter_state_text(profile: ClientProfile) -> str:
    """Состояние фильтров словами для промпта."""
    if profile.debt_amount is None:
        debt = "не указан"
    elif qualifies_by_debt(profile.debt_amount):
        debt = f"{profile.debt_amount} ₽ (подходит)"
    else:
        debt = f"{profile.debt_amount} ₽ (меньше {_rub(MIN_DEBT_RUB)} ₽)"
    if profile.region is None:
        region = "не указан"
    elif is_excluded_region(profile.region):
        region = f"{profile.region} (не обслуживается)"
    else:
        region = f"{profile.region} (подходит)"
    passed = "пройдены" if profile.filters_ok() else "не пройдены"
    return f"долг: {debt}; регион: {region}; фильтры: {passed}"


def profile_text(profile: ClientProfile) -> str:
    """Что известно о клиенте, для промпта."""
    parts: list[str] = []
    if profile.debt_amount is not None:
        parts.append(f"сумма долга: {profile.debt_amount} ₽")
    if profile.region:
        parts.append(f"регион: {profile.region}")
    if profile.phone:
        parts.append(f"телефон: {profile.phone}")
    elif profile.phone_raw:
        parts.append(f"телефон назван неполно: {profile.phone_raw}")
    if profile.consultation_time:
        parts.append(f"удобное время: {profile.consultation_time}")
    if profile.facts:
        parts.append("; ".join(f"{key}: {value}" for key, value in profile.facts.items()))
    return "; ".join(parts) if parts else "(пока ничего)"


def build_user_message(
    *,
    question: str,
    profile: ClientProfile,
    fragments: str,
) -> str:
    """Реплика для модели: фильтры → что знаем о клиенте → знания → реплика клиента.

    Никаких указаний «что сказать в конце» здесь нет: вопрос задаёт код, а любая такая строка
    возвращалась модели в ответ дословно («В конце задать вопрос об общей сумме долга»).
    """
    parts = [
        f"{FILTERS_LABEL}: {filter_state_text(profile)}",
        f"{CLIENT_LABEL}: {profile_text(profile)}",
    ]
    if fragments:
        parts.append(f"{FRAGMENTS_HEADER}\n{fragments}")
    parts.append(f"{QUESTION_LABEL}: {question.strip()}")
    return "\n\n".join(parts)


