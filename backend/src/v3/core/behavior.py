def known_facts(profile: ClientProfile) -> list[str]:
    """Что уже известно о клиенте — для плашки «известно» (сейчас скрыто в контракте)."""
    facts: list[str] = []
    if profile.debt_amount is not None:
        facts.append(f"сумма долга: {profile.debt_amount} ₽")
    if profile.region:
        facts.append(f"регион: {profile.region}")
    if profile.phone:
        facts.append(f"телефон: {profile.phone}")
    if profile.consultation_time:
        facts.append(f"время: {profile.consultation_time}")
    return facts
